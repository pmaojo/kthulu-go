func TestMarkGenerated_CommentSyntaxPerFileType(t *testing.T) {
	cases := []struct {
		path, content, want string
	}{
		{"internal/x/x.go", "package x\n", "// Code generated by kthulu. DO NOT EDIT.\n\npackage x\n"},
		{"internal/views/a.templ", "package views\n", "// Code generated by kthulu. DO NOT EDIT.\npackage views\n"},
		{".github/workflows/ci.yaml", "name: ci\n", "# Code generated by kthulu. DO NOT EDIT.\nname: ci\n"},
		{"Makefile", "build:\n", "# Code generated by kthulu. DO NOT EDIT.\nbuild:\n"},
		{"Dockerfile", "FROM x\n", "# Code generated by kthulu. DO NOT EDIT.\nFROM x\n"},
		{"migrations/1_x.sql", "CREATE TABLE x();\n", "-- Code generated by kthulu. DO NOT EDIT.\nCREATE TABLE x();\n"},
		{"scripts/build.sh", "#!/bin/bash\nset -e\n", "#!/bin/bash\n# Code generated by kthulu. DO NOT EDIT.\nset -e\n"},
	}
	for _, c := range cases {
		got := MarkGenerated(c.path, c.content)
		assert.Equal(t, c.want, got, c.path)
		assert.True(t, HasGeneratedHeader(got), c.path)
		assert.Equal(t, got, MarkGenerated(c.path, got), "marking must be idempotent: %s", c.path)
	}
}

